"""Turn Churn.png (flat cream background) into transparent, separately animatable layers.

    python scripts/prepare_churn_illustration.py [Churn.png]

1. "Colour to alpha": every pixel's distance from the cream background becomes its opacity, so the
   drawing sits on any page colour with no visible rectangle (soft edges and the pink blush survive).
2. The drawing is split into layers (boy, girl, three departing children, tension marks, dotted
   trail) so the front end can move them independently.
3. Each layer is cropped to its bounding box and written as WebP at half resolution, together with
   `layers.ts`, which records where every layer sits on the original 2048 x 1152 canvas.

Needs Pillow, NumPy and SciPy (all present in the project's ML environment).
"""

import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage as ndi

SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("Churn.png")
OUT = Path("frontend/src/assets/churn")
SCALE = 0.5  # output resolution relative to the source (the art is shown at ~500 px wide, 2x for retina)

BACKGROUND = np.array([253, 245, 234], dtype=np.float32)  # the flat cream behind the drawing
SPLIT_X = 1262  # where the boy's hand meets the girl's, in source pixels


def color_to_alpha(rgb: np.ndarray) -> np.ndarray:
    """Returns RGBA float array (0..255 colour, 0..1 alpha)."""
    alpha = np.clip(((BACKGROUND - rgb) / BACKGROUND).max(axis=2), 0, 1)
    safe = np.maximum(alpha, 1e-3)[..., None]
    color = np.clip((rgb - BACKGROUND * (1 - safe)) / safe, 0, 255)
    return np.dstack([color, alpha])


def main() -> None:
    rgb = np.asarray(Image.open(SRC).convert("RGB")).astype(np.float32)
    h, w = rgb.shape[:2]
    rgba = color_to_alpha(rgb)
    alpha = rgba[..., 3]

    # Group strokes into pieces: dilate so a figure's separate strokes join, then label
    solid = alpha > 0.10
    labels, n = ndi.label(ndi.binary_dilation(solid, iterations=7))
    boxes = ndi.find_objects(labels)
    areas = ndi.sum(solid, labels, index=np.arange(1, n + 1))
    xs = np.arange(w)[None, :].repeat(h, axis=0)

    layer_of = np.full(n + 1, "", dtype=object)  # label -> layer name
    for i, sl in enumerate(boxes, start=1):
        x0, x1, area = sl[1].start, sl[1].stop, areas[i - 1]
        if area > 100_000:
            layer_of[i] = "figures"  # boy + girl, split below
        elif x0 >= 1900 and area > 800:
            layer_of[i] = "kid4"
        elif x0 >= 1780 and area > 2000:
            layer_of[i] = "kid3"
        elif x0 >= 1560 and area > 10_000:
            layer_of[i] = "kid2"
        elif x1 <= 1100:
            layer_of[i] = "marks"  # little tension lines around the boy
        elif 1500 <= x0 <= 1560 and area < 500:
            layer_of[i] = "girl"  # the three "!" ticks over the girl's head
        else:
            layer_of[i] = "trail"  # the dotted path of the departing children

    names = np.where(labels > 0, layer_of[labels], "")
    names = np.where(names == "figures", np.where(xs < SPLIT_X, "boy", "girl"), names)

    OUT.mkdir(parents=True, exist_ok=True)
    meta: dict[str, dict[str, float]] = {}
    for name in ["boy", "marks", "girl", "kid2", "kid3", "kid4", "trail"]:
        sel = names == name
        if not sel.any():
            raise SystemExit(f"layer {name} is empty: the component rules need adjusting")
        ys, xs_ = np.where(sel)
        y0, y1, x0, x1 = ys.min(), ys.max() + 1, xs_.min(), xs_.max() + 1
        layer = rgba.copy()
        layer[..., 3] = np.where(sel, alpha, 0)
        crop = layer[y0:y1, x0:x1]
        img = Image.fromarray(np.dstack([crop[..., :3], crop[..., 3:] * 255]).astype(np.uint8), "RGBA")
        img = img.resize((max(1, round(img.width * SCALE)), max(1, round(img.height * SCALE))), Image.LANCZOS)
        img.save(OUT / f"{name}.webp", "WEBP", quality=90, alpha_quality=100, method=6)
        meta[name] = {"x": x0 / w * 100, "y": y0 / h * 100, "w": (x1 - x0) / w * 100, "h": (y1 - y0) / h * 100}
        print(f"{name:6s} {img.width:4d}x{img.height:<4d} at ({x0}, {y0})  {(OUT / f'{name}.webp').stat().st_size // 1024} kB")

    lines = [
        "// Generated by scripts/prepare_churn_illustration.py. Do not edit by hand.",
        "// Position and size of each layer as a percentage of the original 2048 x 1152 canvas.",
        f"export const CANVAS = {{ width: {w}, height: {h} }} as const",
        "export const LAYERS = " + json.dumps({k: {a: round(b, 3) for a, b in v.items()} for k, v in meta.items()}, indent=2) + " as const",
        "",
    ]
    (OUT / "layers.ts").write_text("\n".join(lines), encoding="utf-8")
    print("wrote", OUT / "layers.ts")

    # Preview: all layers composited over the page colour, to check nothing is lost or tinted
    page = np.array([245, 242, 235], dtype=np.float32)
    out = rgb * 0 + page
    out = out * (1 - alpha[..., None]) + rgba[..., :3] * alpha[..., None]
    Image.fromarray(out.astype(np.uint8)).resize((w // 2, h // 2)).save(OUT.parent.parent.parent.parent / "scratch_preview.png")


if __name__ == "__main__":
    main()
